#!/usr/bin/env node
/**
 * Runs every phase gate (00 → 12) sequentially.
 *
 * Honours project rule 7: if any gate fails, stop immediately. The failing
 * gate's completion report is left at the project root with the failure
 * details; gates further down in the chain are NOT attempted.
 *
 * Usage:
 *   npm run phase:all:gates
 *   npm run phase:all:gates -- --continue   # run all of them, do not stop on failure
 *   npm run phase:all:gates -- --from=3     # skip 0-2 (already green)
 *   npm run phase:all:gates -- --through=5  # stop after phase 5
 *
 * Each phase gate writes its own PHASE_NN_COMPLETION_REPORT.md.
 */
import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const arg = (name, def) => {
  const m = argv.find((a) => a.startsWith(name + "="));
  return m ? m.slice(name.length + 1) : def;
};

const CONTINUE = flag("--continue");
const FROM     = Number(arg("--from", "0"));
const THROUGH  = Number(arg("--through", "17"));

const PHASES = [
  { id: 0,  title: "Baseline safety",                              cmd: ["scripts/phase-00-gate.mjs"] },
  { id: 1,  title: "Security launch blockers",                      cmd: ["scripts/phase-01-gate.mjs"] },
  { id: 2,  title: "CI + calculation tests",                         cmd: ["scripts/phase-02-gate.mjs"] },
  { id: 3,  title: "Money as paise integers",                       cmd: ["scripts/phase-03-gate.mjs"] },
  { id: 4,  title: "Indexed sync + payload validation",             cmd: ["scripts/phase-04-gate.mjs"] },
  { id: 5,  title: "Financial event/effect ledger",                 cmd: ["scripts/phase-05-gate.mjs"] },
  { id: 6,  title: "Smart transaction form + balance engine",       cmd: ["scripts/phase-06-gate.mjs"] },
  { id: 7,  title: "Credit-card intelligence engine",               cmd: ["scripts/phase-07-gate.mjs"] },
  { id: 8,  title: "Loan & EMI intelligence engine",                cmd: ["scripts/phase-08-gate.mjs"] },
  { id: 9,  title: "Udhari receivable/payable engine",              cmd: ["scripts/phase-09-gate.mjs"] },
  { id: 10, title: "Goals, emergency, smart budgets, cashflow",     cmd: ["scripts/phase-10-gate.mjs"] },
  { id: 11, title: "Explainable AI suggestion engine",              cmd: ["scripts/phase-11-gate.mjs"] },
  { id: 12, title: "Dashboard, colors, reports, UX polish",         cmd: ["scripts/phase-12-gate.mjs"] },
  { id: 13, title: "Privacy, compliance, audit, retention",         cmd: ["scripts/phase-13-gate.mjs"] },
  { id: 14, title: "SaaS billing fairness + feature gating",        cmd: ["scripts/phase-14-gate.mjs"] },
  { id: 15, title: "Premium CA reports + business/personal",        cmd: ["scripts/phase-15-gate.mjs"] },
  { id: 16, title: "Persona-aware AI coach",                        cmd: ["scripts/phase-16-gate.mjs"] },
  { id: 17, title: "Staging, monitoring, backup, launch readiness", cmd: ["scripts/phase-17-gate.mjs"] },
];

function run(script) {
  return new Promise((resolve) => {
    const child = spawn("node", [script], { cwd: ROOT, stdio: "inherit" });
    child.on("exit", (code) => resolve({ code, ok: code === 0 }));
    child.on("error", () => resolve({ code: -1, ok: false }));
  });
}

const results = [];

for (const p of PHASES) {
  if (p.id < FROM || p.id > THROUGH) continue;
  const head = `\n╔═══ PHASE ${String(p.id).padStart(2, "0")} — ${p.title} ═══`;
  console.log("\n" + "═".repeat(72));
  console.log(head);
  console.log("═".repeat(72));
  const r = await run(p.cmd[0]);
  results.push({ ...p, ...r });
  if (!r.ok && !CONTINUE) {
    console.log(`\n✗ Phase ${p.id} FAILED. Stopping (use --continue to keep going).`);
    break;
  }
}

// Summary
const total = results.length;
const passed = results.filter((r) => r.ok).length;
console.log("\n" + "═".repeat(72));
console.log(`SUMMARY: ${passed}/${total} phase gates passed`);
console.log("═".repeat(72));
for (const r of results) {
  const tag = r.ok ? "✅" : "❌";
  console.log(`  ${tag} Phase ${String(r.id).padStart(2, "0")} — ${r.title}`);
}

// Write a master index
const indexLines = [
  "# Phase Gate Index",
  "",
  `_Generated by \`scripts/phase-all-gates.mjs\` at ${new Date().toISOString()}._`,
  "",
  `**${passed}/${total} phase gates passed.**`,
  "",
  "| Phase | Title | Status | Report |",
  "|---|---|---|---|",
  ...results.map((r) => `| ${r.id} | ${r.title} | ${r.ok ? "✅ PASS" : "❌ FAIL"} | [PHASE_${String(r.id).padStart(2, "0")}_COMPLETION_REPORT.md](./PHASE_${String(r.id).padStart(2, "0")}_COMPLETION_REPORT.md) |`),
  "",
  "## How to use",
  "",
  "Run a single phase: `npm run phase:0X:gate`.",
  "Run everything: `npm run phase:all:gates`.",
  "Skip already-green phases: `npm run phase:all:gates -- --from=3`.",
  "Don't stop on the first failure: `npm run phase:all:gates -- --continue`.",
  "",
  "## Project rule 7",
  "",
  "> Do not move to the next phase until the current phase gate is 100% passed.",
  "",
  "Each PHASE_NN_COMPLETION_REPORT.md contains a Manual Verification section.",
  "Automated PASS is necessary but not sufficient — tick every manual checkbox",
  "before declaring the phase complete.",
  "",
].join("\n");

await fs.writeFile(path.join(ROOT, "PHASE_GATE_INDEX.md"), indexLines, "utf8");
console.log("\nWrote PHASE_GATE_INDEX.md");

process.exit(passed === total ? 0 : 1);
