/**
 * Shared helpers for every per-phase gate runner under scripts/phase-NN-gate.mjs.
 *
 * Each phase gate runner is a small driver that:
 *   1. asserts a list of files/directories exists,
 *   2. runs a few npm scripts (typecheck/lint/test/build/check:php),
 *   3. optionally runs a phase-specific vitest target,
 *   4. records pass/fail/skip per check,
 *   5. writes a Markdown report next to the project root.
 *
 * Usage:
 *   import { runGate } from "./lib/gate-runner.mjs";
 *   await runGate({ phase: 3, title: "Money as paise integers", outPath: "PHASE_03_COMPLETION_REPORT.md", checks: [...] });
 */
import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const isWin = process.platform === "win32";
const NPM = isWin ? "npm.cmd" : "npm";

function ms(d) { return d < 1000 ? `${d}ms` : `${(d/1000).toFixed(1)}s`; }

export async function fileCheck(rel) {
  try { await fs.access(path.join(ROOT, rel)); return { ok: true }; }
  catch { return { ok: false, detail: "missing" }; }
}

export function exec({ cmd, argv, timeoutMs = 240000 }) {
  return new Promise((resolve) => {
    const start = Date.now();
    const child = spawn(cmd, argv, { cwd: ROOT, shell: isWin });
    let buf = "";
    const to = setTimeout(() => { child.kill("SIGKILL"); }, timeoutMs);
    child.stdout?.on("data", (d) => { buf += d.toString(); process.stdout.write(d); });
    child.stderr?.on("data", (d) => { buf += d.toString(); process.stderr.write(d); });
    child.on("error", (e) => {
      clearTimeout(to);
      resolve({ ok: false, code: -1, tail: e.message, ms: Date.now() - start });
    });
    child.on("close", (code) => {
      clearTimeout(to);
      const tail = buf.trim().split("\n").slice(-12).join("\n");
      resolve({ ok: code === 0, code, tail, ms: Date.now() - start });
    });
  });
}

export const npm = (argv) => exec({ cmd: NPM, argv });
export const node = (file, ...rest) => exec({ cmd: "node", argv: [file, ...rest] });

const icon = (s) => s === "pass" ? "✅" : s === "fail" ? "❌" : s === "warn" ? "⚠️" : "⏭️";

export async function runGate({ phase, title, outPath, manualCheckboxes = [], checks }) {
  const id = String(phase).padStart(2, "0");
  console.log(`\nSparowVault — Phase ${id} (${title}) gate runner`);
  const results = [];
  for (const c of checks) {
    process.stdout.write(`  • [${c.section ?? "GATE"}] ${c.name} … `);
    try {
      const r = await c.run();
      results.push({ section: c.section ?? "GATE", name: c.name, status: r.status ?? (r.ok ? "pass" : "fail"), detail: r.detail ?? "" });
      console.log(icon(r.status ?? (r.ok ? "pass" : "fail")));
    } catch (e) {
      results.push({ section: c.section ?? "GATE", name: c.name, status: "fail", detail: e.message });
      console.log("❌");
    }
  }

  const counts = { pass: 0, fail: 0, warn: 0, skip: 0 };
  for (const r of results) counts[r.status] = (counts[r.status] ?? 0) + 1;

  const summary = counts.fail === 0
    ? `✅ all automated checks green (${counts.pass} pass · ${counts.warn} warn · ${counts.skip} skip)`
    : `❌ ${counts.fail} failure(s) (${counts.pass} pass · ${counts.warn} warn · ${counts.skip} skip)`;

  console.log(`\n${summary}`);

  const md = [
    `# PHASE ${id} GATE — ${title}`,
    "",
    `_Generated by \`scripts/phase-${id}-gate.mjs\` at ${new Date().toISOString()}._`,
    "",
    `**Automated outcome: ${summary.startsWith("✅") ? "PASS" : "FAIL"}**`,
    "",
    "## Automated checks",
    "",
    "| Section | Check | Status | Detail |",
    "|---|---|---|---|",
    ...results.map((r) => `| ${r.section} | ${r.name} | ${icon(r.status)} ${r.status} | ${(r.detail ?? "").replace(/\|/g, "\\|").slice(0, 160)} |`),
    "",
    "## Manual verification (developer fills in)",
    "",
    ...(manualCheckboxes.length ? manualCheckboxes.map((line) => `- [ ] ${line}`) : ["- [ ] (none — every check is automated)"]),
    "",
    `## Phase ${id} 100% complete?`,
    "",
    `Automated: ${counts.fail === 0 ? "PASS" : "FAIL"}`,
    "",
    `Manual: ___ / ${manualCheckboxes.length} ticked`,
    "",
    `**Decision:** ${counts.fail === 0 && manualCheckboxes.length === 0 ? "YES (no manual checks required)." : "MARK YES only after every manual checkbox above is ticked."}`,
    "",
  ].join("\n");

  await fs.writeFile(path.join(ROOT, outPath), md, "utf8");
  console.log(`Wrote ${outPath}`);

  if (counts.fail > 0) {
    process.exitCode = 1;
  }

  return { counts, results };
}

// Sugar for "this check is a file-existence assertion"
export function fileExists(rel, label = rel) {
  return {
    section: "FILES",
    name: label,
    async run() {
      const r = await fileCheck(rel);
      return r.ok ? { status: "pass" } : { status: "fail", detail: "missing" };
    },
  };
}

// Sugar for "this check runs `npm run X`"
export function npmScript(scriptName, label = scriptName) {
  return {
    section: "RUN",
    name: label,
    async run() {
      const r = await npm(["run", scriptName]);
      return { status: r.ok ? "pass" : "fail", detail: r.ok ? `exit 0 in ${ms(r.ms)}` : `exit ${r.code}` };
    },
  };
}

// Sugar for "this check runs vitest against a specific file"
export function vitestFile(relTestFile, label) {
  return {
    section: "TEST",
    name: label ?? path.basename(relTestFile),
    async run() {
      const r = await npm(["run", "test", "--", relTestFile]);
      return { status: r.ok ? "pass" : "fail", detail: r.ok ? `exit 0 in ${ms(r.ms)}` : `exit ${r.code}` };
    },
  };
}

// Sugar for "this check reads a file and applies a regex check"
export function fileContains(relPath, regex, label) {
  return {
    section: "FILES",
    name: label ?? `${relPath} contains ${regex}`,
    async run() {
      try {
        const text = await fs.readFile(path.join(ROOT, relPath), "utf8");
        return regex.test(text)
          ? { status: "pass" }
          : { status: "fail", detail: `pattern not found` };
      } catch (e) {
        return { status: "fail", detail: e.message };
      }
    },
  };
}
