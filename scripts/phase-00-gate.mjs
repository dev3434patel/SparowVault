#!/usr/bin/env node
/**
 * PHASE 0 GATE — single-command runner.
 *
 * Runs every check the phase brief requires (in order), captures pass/fail
 * + last few lines of output, and writes a Markdown summary the developer
 * pastes into PHASE_00_COMPLETION_REPORT.md.
 *
 * Manual checks (running the app, registering, adding an expense, etc.) are
 * tracked as ☐ checkboxes — automation cannot fairly substitute for them.
 *
 * Usage:
 *   node scripts/phase-00-gate.mjs
 *   node scripts/phase-00-gate.mjs --out PHASE_00_COMPLETION_REPORT.md
 *
 * Exit codes:
 *   0  — every automated check passed
 *   1  — one or more automated checks failed
 *   2  — internal error (missing binary, IO failure)
 */
import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();

// Determine the platform-correct npm/php executable names
const isWin = process.platform === "win32";
const NPM = isWin ? "npm.cmd" : "npm";

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const OUT = outIdx >= 0 ? args[outIdx + 1] : path.join(ROOT, "PHASE_00_COMPLETION_REPORT.md");

const checks = [
  { name: "npm install",      cmd: NPM, argv: ["install", "--no-audit", "--no-fund"] },
  { name: "npm run typecheck",cmd: NPM, argv: ["run", "typecheck"] },
  { name: "npm run lint",     cmd: NPM, argv: ["run", "lint"] },
  { name: "npm run test",     cmd: NPM, argv: ["run", "test", "--", "--reporter=basic"] },
  { name: "npm run check:php",cmd: NPM, argv: ["run", "check:php"] },
  { name: "npm run check:sql",cmd: NPM, argv: ["run", "check:sql"] },
  { name: "npm run build",    cmd: NPM, argv: ["run", "build"] },
];

function runOne({ name, cmd, argv }) {
  return new Promise((resolve) => {
    const start = Date.now();
    const child = spawn(cmd, argv, { cwd: ROOT, shell: isWin });
    let buf = "";
    child.stdout.on("data", (d) => { buf += d.toString(); process.stdout.write(d); });
    child.stderr.on("data", (d) => { buf += d.toString(); process.stderr.write(d); });
    child.on("error", (err) => {
      resolve({ name, ok: false, ms: Date.now() - start, tail: `spawn error: ${err.message}` });
    });
    child.on("close", (code) => {
      const tail = buf.trim().split("\n").slice(-12).join("\n");
      resolve({ name, ok: code === 0, code, ms: Date.now() - start, tail });
    });
  });
}

function fmtMs(ms) {
  if (ms < 1000) return `${ms}ms`;
  return `${(ms / 1000).toFixed(1)}s`;
}

async function main() {
  const results = [];
  for (const c of checks) {
    console.log(`\n──── ${c.name} ────`);
    const r = await runOne(c);
    results.push(r);
    console.log(`→ ${r.ok ? "✓ PASS" : "✗ FAIL"} (${fmtMs(r.ms)})`);
  }

  const allOk = results.every((r) => r.ok);

  const md = [
    "# PHASE 0 GATE RESULT",
    "",
    `_Generated by \`scripts/phase-00-gate.mjs\` at ${new Date().toISOString()}._`,
    "",
    `**Automated gate: ${allOk ? "✅ ALL PASSED" : "❌ FAIL — see below"}**`,
    "",
    "## Automated checks",
    "",
    "| Check | Result | Duration |",
    "|---|---|---|",
    ...results.map((r) => `| \`${r.name}\` | ${r.ok ? "✅ PASS" : "❌ FAIL"} | ${fmtMs(r.ms)} |`),
    "",
    "## Tail of each check (last 12 lines)",
    "",
    ...results.flatMap((r) => [
      `### ${r.name} — ${r.ok ? "PASS" : "FAIL"}`,
      "",
      "```",
      r.tail || "(no output)",
      "```",
      "",
    ]),
    "## Manual verification (developer fills in)",
    "",
    "Run the app against the **test** database (never production), then tick:",
    "",
    "- [ ] App opens locally (`npm run dev` → http://localhost:5173)",
    "- [ ] User can register (new username + PIN)",
    "- [ ] User can log in with that account",
    "- [ ] User can add a basic expense via QuickAdd",
    "- [ ] Expense appears in Dexie (DevTools → Application → IndexedDB → SparowVaultDB → transactions)",
    "- [ ] Expense syncs to `cloud_collection_rows` (verified via `SELECT * FROM cloud_collection_rows WHERE collection_name='transactions' ORDER BY updated_at DESC LIMIT 5`)",
    "- [ ] Pull works on a simulated second device (open the app in an Incognito window → log in → expense is present)",
    "- [ ] No real secrets are printed in logs (search PHP error log / browser console for `pin`, `pass`, `secret`, `token`)",
    "- [ ] No production dump used in test DB (`TEST_DB_NAME` contains `test`; row counts are tiny)",
    "",
    `## Gate decision`,
    "",
    `Automated: ${allOk ? "PASS" : "FAIL"}`,
    "",
    "Manual: ___ / 8 ticked",
    "",
    `**Phase 0 complete?** ${allOk ? "YES — once 8/8 manual checks are ticked." : "NO — fix failures and re-run."}`,
    "",
  ].join("\n");

  await fs.writeFile(OUT, md, "utf8");
  console.log(`\n✓ Wrote ${path.relative(ROOT, OUT)}`);
  if (!allOk) {
    console.error("\n✗ One or more automated checks failed. Do not proceed to Phase 1.");
    process.exit(1);
  }
}

main().catch((e) => { console.error("Gate runner error:", e); process.exit(2); });
